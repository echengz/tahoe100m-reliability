"""
Runs the reliability regression step. Runs current framework
on prior Wei et al datasets to ensure output is still the
same/consistent with the original.

Focusing on cellular context as that is the version the
current Tahoe100m version was based on.

Takes as input the results of the r-reliability step, as it
needs to conform to how the new framework analyzes systematic
results which uses pre-computed delta-p results.

In general the inheritence this is using is not very clean. The
original BaseSystematicStep base class was intended for the Systematic
and GSEA steps, and as a result SystematicStep was developed more for
Tahoe-100M analysis. For the best regression testing results, we need
to align analysis of the original Wei et al datasets to the new
framework, and therefore derive from this inheritence chain. But there
are several input assumptions we make for Tahoe-100M that are not true for
Wei et al.
"""
import pandas as pd
import time
from pathlib import Path

from tahoe100m_reliability.lib.step.base_systematic_step import DeltaPMode
from tahoe100m_reliability.pipeline.steps.systematic_step import SystematicStep

from .datasets import CELLULAR_DATASETS


class RegressionSystematicStep(SystematicStep):
    """Evaluate systematic on Wei et all datasets."""

    def __init__(
        self,
        reliability_dir: Path,
        output_dir: Path,
        baseline_dir: Path,
    ) -> None:
        """Initializer.

        Raw, CP10K, and clusters have no real meaning in this context, so doing a bit of
        a hack by redefining the initializer/cli args to get around that. This design
        is really not clean though and ideally should be updated. 
        """
        self.name = 'wei_et_al'
        self.datasets = list(CELLULAR_DATASETS.keys())

        self.mode_mapping = {
            # wei et al did apply cp10k, so just call it that for now
            'cp10k': DeltaPMode(reliability_dir, reliability_dir / 'delta_p')
        }
        self.clusters = None

        self.baseline_dir = baseline_dir
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.cur_time = time.strftime('%Y%m%d-%H%M%S')

    @classmethod
    def create_from_args(cls, args: argparse.Namespace) -> "RegressionSystematicStep":
        """Create RegressionSystematicStep from arguments."""
        return cls(**cls.clean_args(args))

    @classmethod
    def add_cli_args(cls, parser: argparse.ArgumentParser) -> None:
        """
        Add CLI args for this systematic step to the given parser.
        Raw vs CP10K has no meaning in this context, so need to redefined arguments a bit.
        """
        parser.add_argument(
            '--reliability-dir', dest='reliability_dir', required=True, type=Path,
            help="Path to the reliability results to serve as input data. Should "
                 + "contain both reliability_summary_*_cluster_*.csv files and delta_p "
                 + "dir, and expected to have been generated by the r-reliability step."
        )

        parser.add_argument(
            '--output-dir', dest='output_dir', required=True, type=Path,
            help='Output directory to write results to'
        )

        parser.add_argument(
            '--baseline-dir', dest='baseline_dir', required=True, type=Path,
            help='Baseline directory containing results to compare to; should contain '
                 + 'systema_* results from the original framework'
        )

    def parse_condition(self, condition: str) -> tuple[str, str]:
        """Parse condition into context and perturbation."""
        parts = condition.split("|")

        if len(parts) != 2:
            raise ValueError(f"Unexpected condition format for Wei et all: {condition}")

        context, perturbation = parts
        return context, perturbation

    def post_per_dataset_processing(
        self, mode: str, ds_name: str, systema_df: pd.DataFrame, merged_df: pd.DataFrame
    ) -> None:
        """Check per-dataset results against baseline."""
        # get baseline (original) results
        baseline_systema_df = pd.read_csv(self.baseline_dir / f'systema_cc_{ds_name}.csv')
        baseline_merged_df = pd.read_csv(self.baseline_dir / f'systema_cc_reliability_2d_{ds_name}.csv')

        # clean up known differences
        # duplicate of the dataset column from old framework's merge, can ignore
        baseline_merged_df = baseline_merged_df.drop(columns=['dataset_rel'])

        # old framework has no context of cluster, we inserted 0 to make it compatible with
        # this framework but can ignore for regression testing
        merged_df = merged_df.drop(columns=['cluster'])

        # make sure types align
        systema_df["n_stim_cells"] = systema_df["n_stim_cells"].astype("int64")
        merged_df["n_stim_cells"] = merged_df["n_stim_cells"].astype("int64")
        baseline_systema_df["context"] = baseline_systema_df["context"].astype("str")
        baseline_merged_df["context"] = baseline_merged_df["context"].astype("str")

        # assert newly generated DFs equal baseline DFs. allow within tolerance due to
        # changes to how the new systematic scores are calculated (pre computed deltas,
        # vectorized calculations, etc.)
        rtol = 1e-6
        atol = 3e-5

        pd.testing.assert_frame_equal(
            systema_df, baseline_systema_df,
            check_exact=False, rtol=rtol, atol=atol,
        )
        pd.testing.assert_frame_equal(
            merged_df, baseline_merged_df,
            check_exact=False, rtol=rtol, atol=atol,
        )

    def run(self) -> None:
        """Run the systematic step and then compare summary results against baseline."""
        super().run()

        summary_df = pd.read_csv(
            self.output_dir / f'systema_cc_cp10k_summary_{self.name}_{self.cur_time}.csv'
        )
        baseline_summary_df = pd.read_csv(self.baseline_dir / 'systema_cc_summary.csv')
        pd.testing.assert_frame_equal(summary_df, baseline_summary_df)
